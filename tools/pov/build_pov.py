"""Build a COULD? POV episode (series "Could you survive...?") into a HyperFrames project.
usage: python3 tools/pov/build_pov.py episodes/<ep>
Reads <ep>/pov.json (dialogue lines placed in time, sfx, music, end card) and <ep>/pov_timing.json (tools/pov/prep.py),
copies the engine + the episode director into <ep>/assets/pov/ and writes <ep>/index.html."""
import html, json, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ep = Path(sys.argv[1]).resolve()
cfg = json.loads((ep / "pov.json").read_text())
timing = json.loads((ep / "pov_timing.json").read_text())
END = cfg["end"]

# engine files
dst = ep / "assets/pov"; dst.mkdir(parents=True, exist_ok=True)
for f in (ROOT / "tools/pov").glob("*.js"): shutil.copy(f, dst / f.name)
shutil.copy(ROOT / "tools/world3d/lib/three.module.min.js", dst / "three.module.min.js")
shutil.copy(ep / "world/director.js", dst / "director.js")

dur = lambda p: float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)], capture_output=True, text=True).stdout)

# looped / faded sfx are rendered to fixed-length files so the timeline only places plain clips
audio = []
who_track = {w: 20 + i for i, w in enumerate(cfg["speakers"])}       # one Studio lane per speaker (lines may overlap a little)
for name, line_t0, who in [(l["id"], l["t0"], l["who"]) for l in timing["lines"]]:
    p = ep / f"assets/voice/{name}.wav"
    audio.append((f"vo-{name}", f"assets/voice/{name}.wav", line_t0, dur(p), who_track[who], 1.0))
(ep / "assets/sfx/out").mkdir(exist_ok=True)
for k, s in enumerate(cfg["sfx"]):
    name, t0, vol = s[0], s[1], s[2]; o = s[3] if len(s) > 3 else {}
    src = ep / f"assets/sfx/{name}.wav"
    if o.get("loop") or o.get("fadeIn") or o.get("fadeOut"):
        length = (o.get("until", t0 + dur(src))) - t0
        out = ep / f"assets/sfx/out/{name}-{k}.wav"
        af = [f"atrim=0:{length:.3f}"]
        if o.get("fadeIn"): af.append(f"afade=t=in:d={o['fadeIn']}")
        af.append(f"afade=t=out:st={max(0, length - o.get('fadeOut', 0.3)):.3f}:d={o.get('fadeOut', 0.3)}")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1" if o.get("loop") else "0", "-i", str(src), "-af", ",".join(af), "-t", f"{length:.3f}", str(out)], check=True)
        audio.append((f"fx-{name}-{k}", f"assets/sfx/out/{name}-{k}.wav", t0, length, 40 + k, vol))
    else:
        audio.append((f"fx-{name}-{k}", f"assets/sfx/{name}.wav", t0, dur(src), 40 + k, vol))
mname, mvol = cfg["music"]
audio.append(("music", f"assets/music/{mname}.wav", 0, END, 19, mvol))

T = {"lines": timing["lines"], "speakers": cfg["speakers"], "end": END}
ec = cfg.get("endCard", {})
opt = lambda o, cls, at: (f'<div class="opt {cls}" data-at="{at}" data-pulse="1"><div class="ob">{html.escape(o["label"])}</div>'
                          f'<div class="os">{html.escape(o["sub"])}</div></div>')
end_html = (f'<div class="kick" data-at="0">{html.escape(ec.get("kicker", "COULD YOU SURVIVE?"))}</div>'
            f'<div class="q" data-at="0.35">{html.escape(ec.get("question", "WHAT WOULD YOU DO?"))}</div>'
            + opt(ec["a"], "a", 1.0) + '<div class="or" data-at="1.5">OR</div>' + opt(ec["b"], "b", 1.9)
            + f'<div class="cta" data-at="2.7">{html.escape(ec.get("cta", "Comment A or B for Part 2"))} <b>↓</b></div>')
clips = "\n".join(f'      <audio id="{i}" class="clip" src="{s}" data-start="{t0:.3f}" data-duration="{d:.3f}" data-track-index="{tr}" data-volume="{v}"></audio>'
                  for i, s, t0, d, tr, v in audio)

page = f"""<!doctype html>
<!-- GENERATED by tools/pov/build_pov.py from pov.json + world/director.js - edit those, not this file. -->
<html lang="en" data-resolution="portrait">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>{html.escape(cfg["title"])}</title>
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ width: 1080px; height: 1920px; overflow: hidden; background: #05070c; }}
      #root {{ position: relative; width: 100%; height: 100%; overflow: hidden; }}
      #pov-gl {{ position: absolute; left: 0; top: 0; width: 1080px; height: 1920px; }}
      .fx {{ position: absolute; inset: 0; pointer-events: none; opacity: 0; }}
      #pov-red {{ background: radial-gradient(ellipse 80% 60% at 50% 50%, rgba(255,40,20,0) 45%, rgba(255,30,10,0.85) 100%); mix-blend-mode: screen; }}
      #pov-black {{ background: #000; }}
      #pov-dim {{ background: linear-gradient(rgba(5,7,12,0.55), rgba(5,7,12,0.85)); }}
      .vig {{ position: absolute; inset: 0; pointer-events: none; background: radial-gradient(ellipse 90% 70% at 50% 48%, transparent 60%, rgba(0,0,0,0.45) 100%); }}
      #pov-hook {{ position: absolute; left: 60px; right: 60px; top: 230px; opacity: 0; font: 900 70px/1.05 "Inter"; color: #fff; text-align: left;
                   text-shadow: 0 4px 0 #000, 0 0 18px rgba(0,0,0,0.8); }}
      #pov-hook b {{ color: #ffd23f; }}
      #pov-cap {{ position: absolute; left: 90px; right: 90px; top: 1590px; text-align: center; opacity: 0; }}
      #pov-tag {{ display: inline-block; margin-bottom: 6px; font: 700 20px/1 "Inter"; letter-spacing: 0.14em; color: rgba(255,255,255,0.6);
                  text-shadow: 0 1px 3px rgba(0,0,0,0.9); }}
      #pov-txt {{ font: 600 38px/1.2 "Inter"; color: #fff; opacity: 0.88; text-shadow: 0 1px 2px rgba(0,0,0,0.95), 0 0 8px rgba(0,0,0,0.6); }}
      #pov-txt span {{ opacity: 1; }}
      #pov-cap.inner #pov-txt {{ font-style: italic; }}
      #pov-end {{ position: absolute; inset: 0; display: none; text-align: center; padding-top: 470px; }}
      #pov-end > div {{ opacity: 0; }}
      #pov-end .kick {{ font: 800 40px/1 "Inter"; letter-spacing: 0.16em; color: #ffd23f; margin-bottom: 26px; }}
      #pov-end .q {{ font: 900 104px/1 "Inter"; color: #fff; text-shadow: 0 6px 0 #000; margin-bottom: 70px; }}
      #pov-end .opt {{ margin: 0 70px; padding: 28px 30px 26px; border-radius: 30px; border: 6px solid #0b0d12; box-shadow: 0 10px 0 #0b0d12; }}
      #pov-end .opt.a {{ background: #22b35a; }} #pov-end .opt.b {{ background: #e0412f; }}
      #pov-end .ob {{ font: 900 70px/1 "Inter"; color: #fff; text-shadow: 0 4px 0 rgba(0,0,0,0.4); }}
      #pov-end .os {{ margin-top: 14px; font: 700 34px/1.2 "Inter"; color: #fff; opacity: 0.95; }}
      #pov-end .or {{ font: 900 44px/1 "Inter"; color: #ffd23f; margin: 30px 0; }}
      #pov-end .cta {{ margin-top: 70px; font: 800 46px/1 "Inter"; color: #fff; }} #pov-end .cta b {{ color: #ffd23f; }}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-case="{cfg['id']}" data-start="0" data-duration="{END}" data-width="1080" data-height="1920">
      <canvas id="pov-gl" width="1080" height="1920"></canvas>
      <div class="vig"></div>
      <div id="pov-red" class="fx"></div>
      <div id="pov-dim" class="fx"></div>
      <div id="pov-hook">{cfg.get("hook", "")}</div>
      <div id="pov-cap"><div id="pov-tag"></div><div id="pov-txt"></div></div>
      <div id="pov-end">{end_html}</div>
      <div id="pov-black" class="fx"></div>
      <script>
        window.__POV = {json.dumps(T)};
        window.__hf = window.__hf || {{}};
        window.__hf.buildReady = window.__hf.buildReady || {{}};
        window.__hf.buildReady.world = new Promise((r) => {{ window.__worldReady = r; }});
      </script>
      <script type="module">
        import {{ createPOV }} from "./assets/pov/engine.js";
        import plot from "./assets/pov/director.js";
        await document.fonts.ready;
        const w = createPOV(plot, window.__POV);
        window.__povRender = (t) => w.renderAt(t);
        window.addEventListener("hf-seek", (e) => w.renderAt(e.detail.time));
        w.renderAt(0);
        window.__worldReady();
      </script>
{clips}
    </div>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
(ep / "index.html").write_text(page)
print(f"wrote {ep / 'index.html'}: {len(audio)} audio clips, {END}s")
